#include <stdio.h>
int main(int argc, char const *argv[])
{
    int num1 = 5;
    int num2 = 3;
    printf("num1+num2=%d\n", num1 + num2);
    printf("num1-num2=%d\n", num1 - num2);
    printf("num1*num2=%d\n", num1 * num2);
    printf("num1/num2=%d\n", num1 / num2);
    printf("num1%%num2=%d\n", num1 % num2);

    float num3 = 3.0F;
    printf("num1/num3=%f\n", num1 / num3);
    return 0;
}

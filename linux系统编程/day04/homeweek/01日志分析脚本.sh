#!/bin/bash
# ============================================================
# 日志分析脚本 log_analyzer.sh
# 功能：读取一个日志目录，遍历所有 .log 文件，
#       统计总行数 / ERROR 行数，并按数量分级输出报告
# ============================================================

# ---------- ① 读入目录路径 ----------
read -p "请输入日志目录路径: " dir

# ---------- ② 判断目录是否存在 ----------
# [ -d "$dir" ] 测试是否为目录；! 取反
if [ ! -d "$dir" ]; then
    echo "目录不存在，退出"
    exit 1
fi

# ---------- ③ 遍历目录下所有 .log 文件 ----------
# "$dir"/*.log 是通配符展开：目录下每个 .log 文件都轮一遍，赋给变量 f
for f in "$dir"/*.log; do

    # 坑：目录里一个 .log 都没有时，通配符不展开，f 会变成字面的 "*.log"
    # 所以先判断 f 到底是不是真文件，不是就跳过本次循环
    [ -f "$f" ] || continue

    # ---------- ④ 统计 ----------
    # wc -l < "$f" ：用输入重定向 <，wc 只输出纯数字（不带文件名）
    # 如果写成 wc -l "$f"，会输出 "12 xxx.log" 这种带文件名的结果，数字就脏了
    total=$(wc -l < "$f")

    # grep -c 统计匹配 "ERROR" 的行数，本身只输出数字
    err=$(grep -c "ERROR" "$f")

    # ---------- ⑤ 分级 ----------
    # case 分支：0 正常，1~5 警告，其余（6 及以上）严重
    case $err in
        0)     level="正常" ;;
        [1-5]) level="警告" ;;
        *)     level="严重" ;;
    esac

    # ---------- ⑥ 输出报告 ----------
    echo "$f | 总行数:$total | ERROR:$err | 级别:$level"
done
